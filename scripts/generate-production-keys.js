#!/usr/bin/env node
/**
 * CMRG Survey — Automated Production Cryptographic Key Generator
 *
 * Designed for VS Code + GitHub Copilot Agent:
 * When prompted to "generate production keys", GitHub Copilot or the engineer
 * runs this script to produce cryptographically strong secrets.
 */

import crypto from 'crypto';
import fs from 'fs';
import path from 'path';

function generateRandomHex(bytes = 32) {
  return crypto.randomBytes(bytes).toString('hex');
}

function generatePassword(length = 24) {
  const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789!@#$%^&*()_+';
  let result = '';
  const randomBytes = crypto.randomBytes(length);
  for (let i = 0; i < length; i++) {
    result += chars[randomBytes[i] % chars.length];
  }
  return result;
}

console.log('\x1b[36m%s\x1b[0m', '=======================================================');
console.log('\x1b[32m%s\x1b[0m', '   CMRG Survey — Production Key Generation Protocol   ');
console.log('\x1b[36m%s\x1b[0m', '=======================================================');

const authSecret = generateRandomHex(32);
const djangoSecret = generateRandomHex(32);
const jwtSigningKey = generateRandomHex(32);
const mobileSyncKey = generateRandomHex(32);
const storageKey = generateRandomHex(32);
const postgresPassword = generatePassword(20);
const adminPassword = generatePassword(18) + '!';

const envContent = `# ==============================================================================
# CMRG Survey — Production Secrets (Generated by Production Key Generator)
# Generated At: ${new Date().toISOString()}
# Configured for VS Code + GitHub Copilot Production Handoff
# ==============================================================================

NODE_ENV=production
PORT=3000

# 1. Express / JWT Authentication Secret (HS256 64-character entropy)
AUTH_SECRET=${authSecret}

# 2. PostgreSQL 16 Production Database Credentials
POSTGRES_DB=cmrg_survey
POSTGRES_USER=cmrg_admin
POSTGRES_PASSWORD=${postgresPassword}
DATABASE_URL=postgresql://cmrg_admin:${postgresPassword}@localhost:5432/cmrg_survey

# 3. Mobile Synchronization Token Secret (CMRG Collect Android)
CMRG_COLLECT_SYNC_SECRET=${mobileSyncKey}
CMRG_MOBILE_SYNC_KEY=${mobileSyncKey}

# 4. Storage & Media Encryption (AES-256 GCM)
STORAGE_SECRET_KEY=${storageKey}
STORAGE_PROVIDER=local
STORAGE_LOCAL_DIR=./uploads/media

# 5. Central Administrator Initial Bootstrap Password
ADMIN_INITIAL_PASSWORD=${adminPassword}

# 6. Django 5.0 Production Settings
DJANGO_SECRET_KEY=${djangoSecret}
SIMPLE_JWT_SIGNING_KEY=${jwtSigningKey}
ALLOWED_HOSTS=*

# 7. Optional Gemini AI API Key (Set by developer if AI Form Assistant is enabled)
GEMINI_API_KEY=
`;

const envPath = path.join(process.cwd(), '.env');
fs.writeFileSync(envPath, envContent, 'utf-8');

console.log('\x1b[32m%s\x1b[0m', '✔ Successfully generated cryptographic production keys!');
console.log('\x1b[33m%s\x1b[0m', `✔ Written securely to: ${envPath}`);
console.log('');
console.log('SUMMARY OF GENERATED KEYS (Keep confidential):');
console.log(`- AUTH_SECRET:             ${authSecret.slice(0, 8)}... (64 hex chars)`);
console.log(`- DJANGO_SECRET_KEY:       ${djangoSecret.slice(0, 8)}... (64 hex chars)`);
console.log(`- SIMPLE_JWT_SIGNING_KEY:  ${jwtSigningKey.slice(0, 8)}... (64 hex chars)`);
console.log(`- CMRG_COLLECT_SYNC_SECRET:${mobileSyncKey.slice(0, 8)}... (64 hex chars)`);
